def _condition(left, op, right, days=0, left_days=0):
    return {'left': left, 'op': op, 'right': str(right), 'leftDays': left_days, 'rightDays': days}


def _signal(sid, name, conditions, inputs, ohlc=0):
    return {'id': sid, 'name': name, 'kind': 'entry', 'timeframe': 'daily',
            'enabled': True, 'conditions': conditions,
            'data_contract': {'version': 1, 'inputs': inputs, 'ohlc_window': ohlc}}


